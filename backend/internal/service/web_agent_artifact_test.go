func TestWebAgentArtifactStoreIsPrivateAndBounded(t *testing.T) {
	root := filepath.Join(t.TempDir(), "private-artifacts")
	store, err := NewWebAgentFileStore(root)
	require.NoError(t, err)
	key, err := store.Put(context.Background(), "docx", []byte("test"))
	require.NoError(t, err)
	info, err := os.Stat(filepath.Join(root, key))
	require.NoError(t, err)
	require.Equal(t, os.FileMode(0600), info.Mode().Perm())
	reader, size, err := store.Open(context.Background(), key)
	require.NoError(t, err)
	require.Equal(t, int64(4), size)
	data, err := io.ReadAll(reader)
	reader.Close()
	require.NoError(t, err)
	require.Equal(t, "test", string(data))
	_, _, err = store.Open(context.Background(), "../etc/passwd")
	require.ErrorIs(t, err, ErrWebAgentInvalid)
	_, err = store.Put(context.Background(), "../txt", []byte("bad"))
	require.ErrorIs(t, err, ErrWebAgentInvalid)
	require.NoError(t, store.Remove(context.Background(), key))
	require.NoError(t, store.Remove(context.Background(), key))
	require.NoError(t, os.Chmod(root, 0755))
	_, err = NewWebAgentFileStore(root)
	require.ErrorIs(t, err, ErrWebAgentInvalid)
}

