func TestWebAgentArtifactRejectsOverflowedSize(t *testing.T) {
	a := &WebAgentArtifact{Kind: "document", Title: "test", Filename: "test.docx", MIME: webAgentArtifactTypes["document"].mime,
		BlobKey: "ffffffff-ffff-ffff-ffff-ffffffffffff.docx", PreviewKey: "ffffffff-ffff-ffff-ffff-ffffffffffff.pdf",
		SizeBytes: math.MaxInt64, PreviewBytes: math.MaxInt64, SHA256: strings.Repeat("a", 64), Spec: json.RawMessage(`{"kind":"document","title":"test"}`)}
	require.ErrorIs(t, a.Validate(), ErrWebAgentInvalid)
}
