func officeArchive(t *testing.T, extra map[string]string) []byte {
	t.Helper()
	var out bytes.Buffer
	z := zip.NewWriter(&out)
	parts := map[string]string{"[Content_Types].xml": "<Types/>", "word/document.xml": "<document/>"}
	for k, v := range extra {
		parts[k] = v
	}
	for k, v := range parts {
		w, err := z.Create(k)
		require.NoError(t, err)
		_, err = io.WriteString(w, v)
		require.NoError(t, err)
	}
	require.NoError(t, z.Close())
	return out.Bytes()
}
func TestWebAgentOfficeClientValidatesIntegrity(t *testing.T) {
	content := officeArchive(t, nil)
	token := strings.Repeat("x", 32)
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		require.Equal(t, "Bearer "+token, r.Header.Get("Authorization"))
		require.Equal(t, "/render", r.URL.Path)
		json.NewEncoder(w).Encode(map[string]any{"protocol_version": 1, "extension": "docx", "mime": webAgentArtifactTypes["document"].mime,
			"file_base64": content, "file_sha256": fmt.Sprintf("%x", sha256.Sum256(content)), "size_bytes": len(content), "preview_pdf_base64": []byte("%PDF-1.7\n")})
	}))
	defer server.Close()
	client, err := NewWebAgentOfficeClient(server.URL, token)
	require.NoError(t, err)
	result, err := client.Render(context.Background(), "document", json.RawMessage(`{"kind":"document","title":"test","sections":[]}`))
	require.NoError(t, err)
	require.Equal(t, content, result.File)
	_, err = client.Render(context.Background(), "slides", json.RawMessage(`{"kind":"document"}`))
	require.ErrorIs(t, err, ErrWebAgentInvalid)
}
func TestWebAgentOfficeClientDoesNotForwardSecretsOnRedirect(t *testing.T) {
	hit := false
	target := httptest.NewServer(http.HandlerFunc(func(http.ResponseWriter, *http.Request) { hit = true }))
	defer target.Close()
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		http.Redirect(w, r, target.URL, http.StatusTemporaryRedirect)
	}))
	defer server.Close()
	client, err := NewWebAgentOfficeClient(server.URL, strings.Repeat("s", 32))
	require.NoError(t, err)
	_, err = client.Render(context.Background(), "document", json.RawMessage(`{"kind":"document"}`))
	require.Error(t, err)
	require.False(t, hit)
}
